#!/usr/bin/env python3
"""Generate the runtime's name tables (nothing here comes from the game).

  gml_functions.h  GML_FUNCTIONS(X): every builtin defined as `Value bi_<name>(Ctx...` in runtime/*.cpp
  gml_names.inc    GM's builtin variable names and constants, from tools/transpiler/gm_builtins.json

usage: gen_tables.py <runtime dir> <gm_builtins.json> <out dir>
"""
import glob
import json
import os
import re
import sys


def write_if_changed(path, text):
    if os.path.exists(path) and open(path).read() == text:
        return
    open(path, 'w').write(text)


def main():
    runtime, names_json, out = sys.argv[1:4]
    os.makedirs(out, exist_ok=True)
    fns = set()
    for f in sorted(glob.glob(os.path.join(runtime, '*.cpp'))):
        fns.update(re.findall(r'^Value bi_(\w+)\(Ctx', open(f).read(), re.M))
    text = ('// generated by tools/gen_tables.py -- do not edit\n#pragma once\n#define GML_FUNCTIONS(X) \\\n'
            + ' \\\n'.join(f'    X({n})' for n in sorted(fns)) + '\n')
    write_if_changed(os.path.join(out, 'gml_functions.h'), text)

    gm = json.load(open(names_json))
    lines = ['// generated by tools/gen_tables.py -- do not edit',
             'static const char* const GM_BUILTIN_VAR_NAMES[] = {']
    lines += [f'    "{n}",' for n in gm['builtin_vars']]
    lines += ['};', 'static const struct { const char* name; double value; } GM_CONSTANTS[] = {']
    lines += [f'    {{"{k}", {float(v)!r}}},' for k, v in sorted(gm['constants'].items())]
    lines += ['};', '']
    write_if_changed(os.path.join(out, 'gml_names.inc'), '\n'.join(lines))


if __name__ == '__main__':
    main()
